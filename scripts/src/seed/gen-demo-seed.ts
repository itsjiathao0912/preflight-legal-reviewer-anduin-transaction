// seed:gen — generates (1) apps/worker/migrations/0003_reference_seed.sql from core ISSUE_CLASSES,
// LAW_FIRMS and normalizeFirmAlias, and (2) apps/worker/seed/demo.sql from a DemoSeedSpec using
// core fingerprint/mask code, so seeds can never drift from the real formula.
// Spec per output (demo-readiness 17-10-26): apps/worker/seed/demo.sql (applied to the deployed
// D1) is ALWAYS built from fixtures/memory/demo-seed-spec.json (Partners Group, quotes from
// bundled samples #3/#5/#6); apps/worker/seed/test-seed.sql (Worker vitest fixture only, Firm X/Y)
// is built from fixtures/memory/_test-seed-spec.json. Each file records its spec path in its
// header; seed:check requires each file to record its own expected spec.
// Every statement is emitted on one line (the worker test setup splits on newlines).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  DemoSeedSpecSchema,
  ISSUE_CLASSES,
  ISSUE_CLASS_LABELS,
  LAW_FIRMS,
  fingerprint,
  limits,
  mask,
  normalizeFirmAlias,
  quoteHash,
  sensitiveSpans,
  type DemoSeedSpec,
} from '@aduin/core';

export const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '../../..');
export const REFERENCE_SQL_PATH = 'apps/worker/migrations/0003_reference_seed.sql';
export const DEMO_SQL_PATH = 'apps/worker/seed/demo.sql';
/** Worker vitest seed (Firm X/Y test spec); never applied to a deployed database. */
export const TEST_SQL_PATH = 'apps/worker/seed/test-seed.sql';
export const PHASE02_SPEC = 'fixtures/memory/demo-seed-spec.json';
export const TEST_SPEC = 'fixtures/memory/_test-seed-spec.json';
export const DEMO_WORKSPACE_ID = 'ws_demo';
/** Bump when the seed SQL layout changes (stored in app_meta.seed_version). */
export const SEED_FORMAT_VERSION = 1;
/** Seed ids are copied into sandboxes as `${sandboxId}:${seedId}`; keep them short (<= 64 total). */
const SEED_ID = /^[a-z0-9_-]{1,24}$/;
/** E6: lowercase, charset [a-z0-9:#>-], <= 80 chars, never `|` (the proposal_key delimiter). */
export const PATTERN_KEY = /^[a-z0-9:#>-]{1,80}$/;

export function sqlStr(v: string | null | undefined): string {
  if (v === null || v === undefined) return 'NULL';
  if (/[\r\n]/.test(v) || v.includes('\0'))
    throw new Error(`seed value contains a newline or NUL: ${v.slice(0, 40)}`);
  return `'${v.replace(/'/g, "''")}'`;
}

function sqlInt(v: number | null | undefined): string {
  if (v === null || v === undefined) return 'NULL';
  if (!Number.isSafeInteger(v)) throw new Error(`not an integer: ${v}`);
  return String(v);
}

/** Free text is masked with the core sensitive-span rule before it is stored (R1, AC58). */
export function maskFree(text: string): string {
  return mask(text, sensitiveSpans(text));
}

/**
 * The firms of landed migration 0003 (Variance Phase 03, F2). 0003 is never edited, so its
 * regenerated text must stay byte-identical: firms added later live only in their own migration
 * (0006: hartwell-crane, ostrander-pell, calder-reyes). Do NOT extend this list.
 */
export const REFERENCE_0003_FIRM_IDS: readonly string[] = ['partners-group', 'firm-x', 'firm-y'];

function reference0003Firms(): typeof LAW_FIRMS {
  return LAW_FIRMS.filter((f) => REFERENCE_0003_FIRM_IDS.includes(f.id));
}

export function buildReferenceSql(): string {
  const lines: string[] = [
    '-- GENERATED by scripts/src/seed/gen-demo-seed.ts (pnpm seed:gen). DO NOT EDIT.',
    '-- Phase 04b migration 0003: law firms, aliases and issue classes from @aduin/core.',
  ];
  const aliasOwner = new Map<string, string>();
  for (const f of reference0003Firms()) {
    lines.push(
      `INSERT INTO law_firm (id, canonical_name, name_norm) VALUES (${sqlStr(f.id)}, ${sqlStr(f.name)}, ${sqlStr(normalizeFirmAlias(f.name))});`,
    );
  }
  for (const f of reference0003Firms()) {
    const norms = [...new Set([f.id, f.name, ...f.aliases].map(normalizeFirmAlias))]
      .filter((a) => a.length > 0)
      .sort();
    for (const a of norms) {
      const prev = aliasOwner.get(a);
      if (prev && prev !== f.id) throw new Error(`alias "${a}" maps to ${prev} and ${f.id}`);
      aliasOwner.set(a, f.id);
      lines.push(
        `INSERT INTO law_firm_alias (alias_norm, law_firm_id) VALUES (${sqlStr(a)}, ${sqlStr(f.id)});`,
      );
    }
  }
  ISSUE_CLASSES.forEach((code, i) => {
    lines.push(
      `INSERT INTO issue_class (code, label, sort) VALUES (${sqlStr(code)}, ${sqlStr(ISSUE_CLASS_LABELS[code])}, ${i + 1});`,
    );
  });
  lines.push(
    "INSERT INTO app_meta (key, value, updated_at) VALUES ('schema_version', '3', 0) ON CONFLICT(key) DO UPDATE SET value = excluded.value;",
  );
  return lines.join('\n') + '\n';
}

interface SeedDecisionRow {
  id: string;
  firm: string;
  fingerprint: string;
  quoteHash: string;
  snippet: string;
  spec: DemoSeedSpec['decisions'][number];
}

export function buildDemoSeedSql(spec: DemoSeedSpec, specPath: string): string {
  const firms = new Set(LAW_FIRMS.map((f) => f.id));
  const ws = spec.workspace.id;
  if (ws !== DEMO_WORKSPACE_ID) throw new Error(`demo workspace id must be ${DEMO_WORKSPACE_ID}`);
  const ids = new Set<string>();
  const checkId = (id: string) => {
    if (!SEED_ID.test(id)) throw new Error(`seed id "${id}" must match ${SEED_ID}`);
    if (ids.has(id)) throw new Error(`duplicate seed id "${id}"`);
    ids.add(id);
  };
  const decisions: SeedDecisionRow[] = spec.decisions.map((d) => {
    checkId(d.id);
    if (!firms.has(d.law_firm_id)) throw new Error(`${d.id}: unknown law_firm_id ${d.law_firm_id}`);
    if (d.pattern_key !== undefined && !PATTERN_KEY.test(d.pattern_key))
      throw new Error(`${d.id}: pattern_key violates the E6 charset`);
    // client-side masking of the flagged spans happens before hashing (DATA-MODEL 2.2)
    const masked = mask(d.quote, d.sensitive_spans ?? []);
    const qh = quoteHash(masked);
    return {
      id: d.id,
      firm: d.law_firm_id,
      fingerprint: fingerprint(d.law_firm_id, d.issue_class, qh),
      quoteHash: qh,
      snippet: maskFree(masked).slice(0, limits.snippetMaxChars),
      spec: d,
    };
  });
  const fps = new Set<string>();
  for (const d of decisions) {
    const k = `${d.firm}|${d.fingerprint}`;
    if (fps.has(k)) throw new Error(`${d.id}: two active seed decisions share a fingerprint`);
    fps.add(k);
  }
  for (const r of spec.rules) {
    checkId(r.id);
    if (!firms.has(r.law_firm_id)) throw new Error(`${r.id}: unknown law_firm_id ${r.law_firm_id}`);
    if (r.pattern_key !== undefined && !PATTERN_KEY.test(r.pattern_key))
      throw new Error(`${r.id}: pattern_key violates the E6 charset`);
  }

  const analysts = [...new Set(spec.decisions.map((d) => d.decided_by_name))].sort();
  const analystId = (name: string) => `an_seed${analysts.indexOf(name) + 1}`;
  const at = spec.decisions.length ? Math.min(...spec.decisions.map((d) => d.decided_at)) : 0;

  const out: string[] = [
    `-- GENERATED by scripts/src/seed/gen-demo-seed.ts (pnpm seed:gen). DO NOT EDIT.`,
    `-- spec: ${specPath}`,
    `-- seed_format: ${SEED_FORMAT_VERSION}`,
    `-- Applied once per database with seed_mode=1 (the only time the demo triggers allow writes).`,
    "INSERT INTO app_meta (key, value, updated_at) VALUES ('seed_mode', '1', 0) ON CONFLICT(key) DO UPDATE SET value = excluded.value;",
    `INSERT INTO workspace (id, kind, status, seed_version, created_at, last_active_at, expires_at) VALUES (${sqlStr(ws)}, 'demo', 'active', ${SEED_FORMAT_VERSION}, ${sqlInt(at)}, ${sqlInt(at)}, NULL);`,
  ];
  for (const name of analysts) {
    out.push(
      `INSERT INTO analyst (workspace_id, id, display_name, is_seed, created_at) VALUES (${sqlStr(ws)}, ${sqlStr(analystId(name))}, ${sqlStr(maskFree(name))}, 1, ${sqlInt(at)});`,
    );
  }
  for (const d of decisions) {
    const s = d.spec;
    const cols = [
      sqlStr(ws),
      sqlStr(d.id),
      sqlStr(d.firm),
      sqlStr(d.fingerprint),
      sqlStr(s.issue_class),
      sqlStr(s.pattern_key),
      sqlStr(d.quoteHash),
      sqlStr(d.snippet),
      sqlStr(s.section_path ? JSON.stringify(s.section_path.map(maskFree)) : null),
      sqlStr(maskFree(s.fund_name)),
      sqlStr(s.doc_version_label === undefined ? null : maskFree(s.doc_version_label)),
      sqlStr(s.decision),
      sqlStr(s.reason_code),
      sqlStr(s.note === undefined ? null : maskFree(s.note)),
      sqlStr(s.counsel_option),
      sqlStr(s.counsel_note === undefined ? null : maskFree(s.counsel_note)),
      sqlStr(analystId(s.decided_by_name)),
      sqlStr(maskFree(s.decided_by_name)),
      sqlInt(s.decided_at),
    ];
    out.push(
      `INSERT INTO decision (workspace_id, id, law_firm_id, fingerprint, issue_class, pattern_key, quote_hash, quote_snippet, section_path, fund_name, doc_version_label, decision, reason_code, note, counsel_option, counsel_note, decided_by_analyst_id, decided_by_name, decided_at) VALUES (${cols.join(', ')});`,
    );
  }
  const ruleAt = decisions.length ? Math.max(...spec.decisions.map((d) => d.decided_at)) : at;
  for (const r of spec.rules) {
    const evidence = r.pattern_key
      ? decisions.filter(
          (d) =>
            d.firm === r.law_firm_id &&
            d.spec.pattern_key === r.pattern_key &&
            d.spec.decision === 'dismissed',
        )
      : [];
    const reasons = [...new Set(evidence.map((d) => d.spec.reason_code))];
    const reason = reasons.length === 1 && reasons[0] ? reasons[0] : 'seed';
    const proposalKey = r.pattern_key ? `${r.pattern_key}|${reason}` : null;
    const origin = r.status === 'active' && !r.pattern_key ? 'manual' : 'proposed';
    const decided = r.status === 'proposed' ? null : ruleAt;
    out.push(
      `INSERT INTO firm_rule (workspace_id, id, law_firm_id, origin, status, rule_text, proposal_key, created_by_name, created_at, decided_by_name, decided_at) VALUES (${[
        sqlStr(ws),
        sqlStr(r.id),
        sqlStr(r.law_firm_id),
        sqlStr(origin),
        sqlStr(r.status),
        sqlStr(maskFree(r.text)),
        sqlStr(proposalKey),
        sqlStr('Seed (simulated analyst)'),
        sqlInt(ruleAt),
        sqlStr(decided === null ? null : 'Seed (simulated analyst)'),
        sqlInt(decided),
      ].join(', ')});`,
    );
    for (const d of evidence) {
      out.push(
        `INSERT INTO rule_evidence (workspace_id, rule_id, decision_id, added_at) VALUES (${sqlStr(ws)}, ${sqlStr(r.id)}, ${sqlStr(d.id)}, ${sqlInt(ruleAt)});`,
      );
    }
  }
  // a few seeded audit rows (ids and enums only in detail_json)
  for (const d of decisions) {
    out.push(
      `INSERT INTO audit_event (workspace_id, id, client_op_id, at, analyst_id, actor_name, action, law_firm_id, entity_type, entity_id, detail_json) VALUES (${[
        sqlStr(ws),
        sqlStr(`ae_seed_${d.id}`),
        sqlStr(`seed:${d.id}`),
        sqlInt(d.spec.decided_at),
        sqlStr(analystId(d.spec.decided_by_name)),
        sqlStr(maskFree(d.spec.decided_by_name)),
        sqlStr('decision_recorded'),
        sqlStr(d.firm),
        sqlStr('decision'),
        sqlStr(d.id),
        sqlStr(JSON.stringify({ decision: d.spec.decision, issue_class: d.spec.issue_class })),
      ].join(', ')});`,
    );
  }
  for (const r of spec.rules) {
    out.push(
      `INSERT INTO audit_event (workspace_id, id, client_op_id, at, analyst_id, actor_name, action, law_firm_id, entity_type, entity_id, detail_json) VALUES (${[
        sqlStr(ws),
        sqlStr(`ae_seed_${r.id}`),
        sqlStr(`seed:${r.id}`),
        sqlInt(ruleAt),
        'NULL',
        sqlStr('Seed (simulated analyst)'),
        sqlStr(r.status === 'proposed' ? 'rule_proposed' : 'rule_added'),
        sqlStr(r.law_firm_id),
        sqlStr('rule'),
        sqlStr(r.id),
        sqlStr(JSON.stringify({ status: r.status })),
      ].join(', ')});`,
    );
  }
  out.push(
    `INSERT INTO app_meta (key, value, updated_at) VALUES ('seed_version', '${SEED_FORMAT_VERSION}', 0) ON CONFLICT(key) DO UPDATE SET value = excluded.value;`,
    "INSERT INTO app_meta (key, value, updated_at) VALUES ('seed_mode', '0', 0) ON CONFLICT(key) DO UPDATE SET value = excluded.value;",
  );
  return out.join('\n') + '\n';
}

/** The spec each generated seed file must be built from. */
export const SPEC_FOR: Readonly<Record<string, string>> = Object.freeze({
  [DEMO_SQL_PATH]: PHASE02_SPEC,
  [TEST_SQL_PATH]: TEST_SPEC,
});

export function loadSpec(root: string, specPath: string): DemoSeedSpec {
  const raw: unknown = JSON.parse(readFileSync(resolve(root, specPath), 'utf8'));
  return DemoSeedSpecSchema.parse(raw);
}

export function generate(root: string, specPath: string): { reference: string; demo: string } {
  if (!existsSync(resolve(root, specPath))) throw new Error(`seed spec ${specPath} is missing`);
  return {
    reference: buildReferenceSql(),
    demo: buildDemoSeedSql(loadSpec(root, specPath), specPath),
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const { reference, demo } = generate(ROOT, PHASE02_SPEC);
  const test = generate(ROOT, TEST_SPEC).demo;
  for (const [rel, text] of [
    [REFERENCE_SQL_PATH, reference],
    [DEMO_SQL_PATH, demo],
    [TEST_SQL_PATH, test],
  ] as const) {
    const abs = resolve(ROOT, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
    console.log(`seed:gen: wrote ${rel}${SPEC_FOR[rel] ? ` (spec ${SPEC_FOR[rel]})` : ''}`);
  }
}
