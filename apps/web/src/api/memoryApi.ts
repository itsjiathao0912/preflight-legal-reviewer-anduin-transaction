export type MemoryApiErrorCode =
  | 'invalid_request'
  | 'not_found'
  | 'unavailable'
  | 'read_only'
  | 'unauthorized'
  | 'conflict'
  | 'run_required'
  | 'fingerprint_mismatch'
  | 'rate_limited'
  | 'quota_exhausted';

export interface MemoryApiErrorInit {
  reason?: string;
  status?: number;
  /** ISO-8601 UTC instant after which a 429 may be retried (next UTC day for daily budgets). */
  retryAfterUtc?: string;
  /** 409 conflict: the active decision on the server (null when none). */
  current?: ActiveDecision | null;
}

const DEFAULT_STATUS: Readonly<Record<MemoryApiErrorCode, number>> = Object.freeze({
  invalid_request: 400,
  run_required: 400,
  not_found: 404,
  unavailable: 503,
  read_only: 403,
  unauthorized: 401,
  conflict: 409,
  fingerprint_mismatch: 422,
  rate_limited: 429,
  quota_exhausted: 429,
});

export class MemoryApiError extends Error {
  readonly reason?: string;
  readonly status: number;
  readonly retryAfterUtc?: string;
  readonly current?: ActiveDecision | null;
  constructor(
    readonly code: MemoryApiErrorCode,
    message: string,
    init: MemoryApiErrorInit = {},
  ) {
    super(message);
    this.name = 'MemoryApiError';
    this.status = init.status ?? DEFAULT_STATUS[code];
    if (init.reason !== undefined) this.reason = init.reason;
    if (init.retryAfterUtc !== undefined) this.retryAfterUtc = init.retryAfterUtc;
    if (init.current !== undefined) this.current = init.current;
  }
}

/** Reasons that mark a daily/workspace budget (defer to the next UTC day), not a burst limit. */
export function isDailyBudgetReason(reason: string | undefined): boolean {
  return (
    reason === 'memory_write_budget' ||
    reason === 'session_limit' ||
    (reason !== undefined && reason.startsWith('workspace_'))
  );
}

/** Next UTC midnight after `now` (ISO). */
export function nextUtcDay(now: number): string {
  const d = new Date(now);
  return new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate() + 1)).toISOString();
}

/**
 * Frozen wire -> client error mapping (code + reason + status). The real client feeds every non-2xx
 * `{error:{code,message,reason?,retry_after_s?}, current?}` body through this.
 *
 * | wire code / status                         | client code            |
 * |--------------------------------------------|------------------------|
 * | read_only_demo (403)                       | read_only              |
 * | invalid_session (401)                      | unauthorized           |
 * | conflict_active_decision (409) + current   | conflict (current)     |
 * | invalid_request reason run_required        | run_required           |
 * | invalid_request reason *_not_found         | not_found              |
 * | invalid_request other reasons (400)        | invalid_request(reason)|
 * | fingerprint_mismatch (422)                 | fingerprint_mismatch   |
 * | rate_limited / quota_exhausted (429)       | rate_limited / quota_exhausted (retryAfterUtc) |
 * | memory_unavailable (503), network, other   | unavailable            |
 */
export function toMemoryApiError(
  status: number,
  body: unknown,
  now: number = Date.now(),
): MemoryApiError {
  const b = (body ?? {}) as {
    error?: { code?: string; message?: string; reason?: string; retry_after_s?: number };
    current?: ActiveDecision | null;
  };
  const wire = b.error?.code;
  const reason = b.error?.reason;
  const message = b.error?.message ?? `memory request failed (${status})`;
  const base = { status, ...(reason !== undefined ? { reason } : {}) };
  switch (wire) {
    case 'read_only_demo':
      return new MemoryApiError('read_only', message, base);
    case 'invalid_session':
      return new MemoryApiError('unauthorized', message, base);
    case 'conflict_active_decision':
      return new MemoryApiError('conflict', message, { ...base, current: b.current ?? null });
    case 'fingerprint_mismatch':
      return new MemoryApiError('fingerprint_mismatch', message, base);
    case 'rate_limited':
    case 'quota_exhausted': {
      const s = b.error?.retry_after_s;
      const retryAfterUtc =
        isDailyBudgetReason(reason) || s === undefined
          ? nextUtcDay(now)
          : new Date(now + s * 1000).toISOString();
      return new MemoryApiError(wire, message, { ...base, retryAfterUtc });
    }
    case 'invalid_request':
      if (reason === 'run_required') return new MemoryApiError('run_required', message, base);
      if (reason !== undefined && reason.endsWith('_not_found'))
        return new MemoryApiError('not_found', message, base);
      return new MemoryApiError('invalid_request', message, base);
    default:
      if (status === 404) return new MemoryApiError('not_found', message, base);
      return new MemoryApiError('unavailable', message, base);
  }
}

export interface MemoryApi {
  /** POST /api/session (idempotent for a live sandbox). `analyst_name` 1-80 chars, trimmed. */
  bootstrap(name: string): Promise<SessionInfo>;
  /** Active decisions for these fingerprints (at most limits.memoryLookupMax per call). */
  lookup(lawFirmId: string, fingerprints: string[]): Promise<ActiveDecision[]>;
  /** POST /api/runs (lazy: first write action only). */
  ensureRun(input: EnsureRunInput): Promise<{ run_id: string }>;
  /** POST /api/runs/:id/findings in chunks of FINDINGS_CHUNK; returns the total newly stored. */
  storeFindings(runId: string, findings: FindingWire[]): Promise<{ stored: number }>;
  decide(input: DecideInput): Promise<ActiveDecision>;
  /** One batch of Needs-counsel questions (at export or answer time). */
  createQuestions(runId: string, items: QuestionItem[]): Promise<CreatedQuestion[]>;
  /** Record a counsel answer (writes the answer + a superseding `answered` decision). */
  answer(input: AnswerInput): Promise<ActiveDecision>;
  /** POST /api/runs/:id/export (records sheet_exported_at + question count + audit row). */
  exportRun(runId: string, input: ExportRunInput): Promise<ExportRunResult>;
  /** Revoke (never delete). Returns the decision that is active afterwards (always null in v1). */
  revoke(decisionId: string, reason: string): Promise<ActiveDecision | null>;
  /**
   * Phase 05 (G13): ACTIVE firm rule texts for the AI lane (plain strings handed to the engine worker).
   * Real client: GET /api/memory/firm?law_firm_id= filtered to `status === 'active'`.
   */
  firmRules(lawFirmId: string): Promise<string[]>;
  // --- pinned 08b signatures (08b only consumes them) ---
  /** GET /api/memory/firm?law_firm_id= */
  firm(lawFirmId: string): Promise<FirmMemoryResponse>;
  /** GET /api/rules?law_firm_id= */
  listRules(lawFirmId: string): Promise<Rule[]>;
  /** POST /api/rules?law_firm_id= (manual rule, active). */
  createRule(lawFirmId: string, text: string): Promise<Rule>;
  approveRule(id: string): Promise<Rule>;
  rejectRule(id: string): Promise<Rule>;
  revokeRule(id: string, text: string): Promise<Rule>;
  /** GET /api/audit?limit=AUDIT_PAGE_SIZE&cursor= */
  audit(cursor?: string): Promise<AuditPage>;
  /** GET /api/memory/health */
  health(): Promise<MemoryHealth>;
}

/** Outbox op lifecycle (Phase 08 `outbox.ts`): queued -> sending -> synced | retry | deferred | rejected. */
export type OutboxState = 'queued' | 'sending' | 'synced' | 'retry' | 'deferred' | 'rejected';
